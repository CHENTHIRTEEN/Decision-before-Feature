def _finish_online_row(
    *,
    policy_name: str,
    function: int,
    dimension: int,
    seed: int,
    tracker: PathEvaluationTracker,
    started: float,
    fe_total: int,
    selected_algorithm: str,
    query_called: bool,
    trigger_fe: int | None,
    decision_score: float | None,
    decision_threshold: float | None,
    decision_check_count: int,
    failure: str = "",
    selector_scores: np.ndarray | None = None,
) -> dict[str, Any]:
    runtime = float(perf_counter() - started)
    reference = float(tracker.benchmark_reference_value)
    final_gap = max(float(tracker.best_all) - reference, 0.0)
    target_hit = tracker.first_hit_fe is not None
    completed = not failure and int(tracker.total_evaluations) == int(fe_total)
    clipped = max(min(final_gap, 1.0e20), 1.0e-12)
    selected_equals_prefix = selected_algorithm == PREFIX_ALGORITHM
    row = {
        "policy_name": policy_name,
        "suite": "cec2017",
        "function": int(function),
        "dimension": int(dimension),
        "seed": int(seed),
        "prefix_algorithm": PREFIX_ALGORITHM,
        "default_algorithm": PREFIX_ALGORITHM,
        "selected_algorithm": selected_algorithm,
        "selected_action": "continue_current" if selected_equals_prefix else selected_algorithm,
        "selected_equals_prefix": bool(selected_equals_prefix),
        "handoff_required": bool(not selected_equals_prefix),
        "handoff_type": "native_optimizer_state" if selected_equals_prefix else "population_transfer_initialization",
        "query_called": bool(query_called),
        "trigger_FE": trigger_fe,
        "trigger_FE_ratio": (float(trigger_fe) / float(fe_total)) if trigger_fe is not None else None,
        "decision_score": decision_score,
        "decision_threshold": decision_threshold,
        "decision_check_count": int(decision_check_count),
        "selector_scores_de": None if selector_scores is None else float(selector_scores[0]),
        "selector_scores_pso": None if selector_scores is None else float(selector_scores[1]),
        "selector_scores_lshade": None if selector_scores is None else float(selector_scores[2]),
        "FE_total": int(fe_total),
        "FE_used": int(tracker.total_evaluations),
        "FE_prefix": int(tracker.prefix_evaluations),
        "FE_query": int(tracker.query_evaluations),
        "FE_after": int(tracker.continuation_evaluations),
        "first_hit_FE": tracker.first_hit_fe,
        "first_hit_wall_clock_seconds": tracker.first_hit_wall_clock_seconds,
        "target_hit_observed": bool(target_hit),
        "endpoint_success": bool(target_hit and completed),
        "final_gap": float(final_gap),
        "log10_gap": float(np.log10(clipped)),
        "runtime_full_run_wall_clock": runtime,
        "time_ert_seconds_contribution": float(tracker.first_hit_wall_clock_seconds if target_hit and tracker.first_hit_wall_clock_seconds is not None else runtime),
        "ert_FE_contribution": int(tracker.first_hit_fe if target_hit else fe_total),
        "path_completed": bool(completed),
        "path_status": "completed" if completed else ("failed" if failure else "incomplete"),
        "failure_message": str(failure),
        "timing_source": "measured_complete_policy_path",
    }
    return row


def _run_controller_path(
    *,
    config: dict[str, Any],
    function: int,
    dimension: int,
    seed: int,
    selector: StatewiseSelectorModel,
    controller: Any,
    query_feature_row: dict[str, Any],
    query_sample_row: dict[str, Any],
    threshold: float,
) -> dict[str, Any]:
    policy_name = "three_algorithm_controller"
    started = perf_counter()
    fe_total = int(config["FE_total_by_dimension"][dimension])
    deadline = started + float(config["policy_timeout_seconds"])
    tracker = PathEvaluationTracker(
        benchmark_reference_value=float(query_sample_row["benchmark_reference_value"]),
        success_gap_target=float(config["success_gap_target"]),
        planned_total_fe=fe_total,
        wall_clock_started_at=started,
    )
    base = None
    failure = ""
    selected_algorithm = PREFIX_ALGORITHM
    trigger_fe = None
    decision_score = None
    selector_scores = None
    decision_checks = 0
    query_called = False
    try:
        base, problem = _base_online_problem(function, dimension, tracker, deadline)
        tracker.set_phase("prefix")
        settings = OptimizerSettings(
            population_size=POPULATION_SIZE,
            checkpoint_ratios=(1.0,),
            boundary_handling="reflect",
        )
        state = initialize_optimizer_state(
            algorithm=PREFIX_ALGORITHM,
            problem=problem,
            seed=int(seed),
            settings=settings,
        )
        behavior_stream = StreamingBehaviorState(
            problem_id=problem.problem_id,
            function_id=problem.function_id,
            family=problem.family,
            dimension=dimension,
            algorithm=PREFIX_ALGORITHM,
            seed=int(seed),
            fe_total=fe_total,
            sampling_protocol=str(config["sampling_protocol"]),
        )
        behavior_stream.observe(
            fe=int(state.evaluations),
            native_updates=int(state.generation),
            population=state.population,
            fitness=state.fitness,
            best_fitness=state.best_fitness,
        )
        fe_query = int(query_sample_row["FE_query"])
        while behavior_stream.next_monitor_ratio is not None:
            delta = min(POPULATION_SIZE, fe_total - int(state.evaluations))
            if delta <= 0:
                break
            advance_optimizer_state(
                state=state,
                problem=problem,
                fe_budget=delta,
                on_native_update=lambda updated: behavior_stream.observe(
                    fe=int(updated.evaluations),
                    native_updates=int(updated.generation),
                    population=updated.population,
                    fitness=updated.fitness,
                    best_fitness=updated.best_fitness,
                ),
            )
            behavior_row = behavior_stream.sample_dynamic()
            if behavior_row is None or int(state.evaluations) + fe_query > fe_total:
                continue
            decision_checks += 1
            decision_score = _controller_score(controller, behavior_row)
            if decision_score <= float(threshold):
                continue
            query_called = True
            trigger_fe = int(state.evaluations)
            tracker.remember(
                query_called=True,
                trigger_FE=trigger_fe,
                trigger_FE_ratio=float(trigger_fe / fe_total),
                decision_score=decision_score,
                decision_threshold=float(threshold),
            )
            query_execution = _execute_real_query(
                problem=problem,
                tracker=tracker,
                deadline=deadline,
                query_feature_row=query_feature_row,
                query_sample_row=query_sample_row,
            )
            tracker.set_phase("continuation")
            remaining = max(fe_total - int(state.evaluations) - fe_query, 0)
            if query_execution.status == "ok":
                query_features = {
                    column: query_execution.features.get(column)
                    for column in selector.query_feature_columns
                }
                selected_algorithm, selector_scores, _ = _online_select(
                    selector,
                    query_features,
                    behavior_row,
                    float(remaining / fe_total),
                )
            else:
                selected_algorithm = PREFIX_ALGORITHM
            if selected_algorithm == PREFIX_ALGORITHM:
                after_state = state
                advance_optimizer_state(state=after_state, problem=problem, fe_budget=remaining)
            elif selected_algorithm == "pso":
                after_state = initialize_transferred_optimizer_state(
                    algorithm="pso",
                    source_state=state,
                    problem=problem,
                    seed=int(seed),
                    function=int(function),
                    instance=1,
                    event=QUERY_TRANSFER_EVENT,
                )
                advance_optimizer_state(state=after_state, problem=problem, fe_budget=remaining)
            elif selected_algorithm == "lshade":
                after_state = _lshade_transfer_state(
                    source_state=state,
                    problem=problem,
                    seed=int(seed),
                    max_evaluations=remaining,
                    event=QUERY_TRANSFER_EVENT,
                )
                advance_lshade_state(state=after_state, problem=problem, fe_budget=remaining)
            else:
                raise ValueError(f"unsupported selected algorithm: {selected_algorithm}")
            return _finish_online_row(
                policy_name=policy_name,
                function=function,
                dimension=dimension,
                seed=seed,
                tracker=tracker,
                started=started,
                fe_total=fe_total,
                selected_algorithm=selected_algorithm,
                query_called=True,
                trigger_fe=trigger_fe,
                decision_score=decision_score,
                decision_threshold=threshold,
                decision_check_count=decision_checks,
                selector_scores=selector_scores,
            )
        remaining = max(fe_total - int(state.evaluations), 0)
        advance_optimizer_state(state=state, problem=problem, fe_budget=remaining)
        return _finish_online_row(
            policy_name=policy_name,
            function=function,
            dimension=dimension,
            seed=seed,
            tracker=tracker,
            started=started,
            fe_total=fe_total,
            selected_algorithm=PREFIX_ALGORITHM,
            query_called=False,
            trigger_fe=None,
            decision_score=None,
            decision_threshold=threshold,
            decision_check_count=decision_checks,
        )
    except Exception as exc:
        failure = f"{type(exc).__name__}: {str(exc)[:500]}"
        return _finish_online_row(
            policy_name=policy_name,
            function=function,
            dimension=dimension,
            seed=seed,
            tracker=tracker,
            started=started,
            fe_total=fe_total,
            selected_algorithm=selected_algorithm,
            query_called=query_called,
            trigger_fe=trigger_fe,
            decision_score=decision_score,
            decision_threshold=threshold,
            decision_check_count=decision_checks,
            failure=failure,
            selector_scores=selector_scores,
        )
    finally:
        if base is not None:
            base.close()


