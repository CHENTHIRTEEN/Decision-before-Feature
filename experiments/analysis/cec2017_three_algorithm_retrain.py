def _load_training_artifacts() -> tuple[StatewiseSelectorModel, Any, dict[str, Any]]:
    summary_path = OUTPUT / "training_summary.json"
    selector_path = OUTPUT / "selector_model.joblib"
    controller_path = OUTPUT / "controller_model.joblib"
    if not summary_path.exists() or not selector_path.exists() or not controller_path.exists():
        raise FileNotFoundError("three-algorithm training artifacts are incomplete")
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    selector = joblib.load(selector_path)
    controller = joblib.load(controller_path)
    if tuple(selector.target_algorithms) != PORTFOLIO:
        raise ValueError("three-algorithm selector artifact has an unexpected action set")
    if tuple(selector.feature_columns) != SELECTOR_FEATURE_COLUMNS:
        raise ValueError("three-algorithm selector feature contract is inconsistent")
    if list(summary["decision_feature_columns"]) != list(DECISION_FEATURE_COLUMNS):
        raise ValueError("three-algorithm controller feature contract is inconsistent")
    return selector, controller, summary


def _controller_score(controller: Any, behavior_row: dict[str, Any]) -> float:
    frame = pd.DataFrame([{column: behavior_row[column] for column in DECISION_FEATURE_COLUMNS}])
    score = float(np.asarray(controller.predict(frame), dtype=float).reshape(-1)[0])
    if not np.isfinite(score):
        raise ValueError("three-algorithm controller returned a non-finite score")
    return score


def _online_select(selector: StatewiseSelectorModel, query_features: dict[str, Any], behavior_row: dict[str, Any], remaining_ratio: float) -> tuple[str, np.ndarray, float]:
    features = make_selector_features(
        behavior_features=behavior_row,
        query_features=query_features,
        query_feature_columns=selector.query_feature_columns,
        remaining_budget_ratio=remaining_ratio,
    )
    frame = pd.DataFrame([{column: features[column] for column in selector.feature_columns}])
    started = perf_counter()
    scores = np.asarray(selector.model.predict(frame[list(selector.feature_columns)]), dtype=float).reshape(-1)
    elapsed = float(perf_counter() - started)
    if scores.shape != (len(PORTFOLIO),) or not np.isfinite(scores).all():
        raise ValueError("three-algorithm Selector returned invalid scores")
    selected = PORTFOLIO[int(np.argmin(scores))]
    return selected, scores, elapsed


