def run(*, workers: int, overwrite: bool, skip_online: bool) -> dict[str, Any]:
    if overwrite and OUTPUT.exists():
        for path in (
            OUTPUT / "training_states.parquet",
            OUTPUT / "selector_model.joblib",
            OUTPUT / "controller_model.joblib",
        ):
            if path.exists():
                path.unlink()
    states = _build_training_states(workers=workers, overwrite=overwrite)
    selector, selector_oof, _ = _fit_selector_models(states)
    training_summary = _fit_controller(states, selector_oof)
    if skip_online:
        return training_summary
    return _run_online(overwrite=overwrite)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workers", type=int, default=min(8, max(1, os.cpu_count() or 1)))
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--skip-online", action="store_true")
    args = parser.parse_args()
    if int(args.workers) < 1:
        raise ValueError("--workers must be at least 1")
    result = run(
        workers=int(args.workers),
        overwrite=bool(args.overwrite),
        skip_online=bool(args.skip_online),
    )
    print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
