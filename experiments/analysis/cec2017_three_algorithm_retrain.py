def _problem_from_id(problem_id: str) -> Any:
    bbob = re.fullmatch(r"bbob_f(\d{3})_i(\d+)_d(\d+)", str(problem_id))
    if bbob:
        function, instance, dimension = (int(value) for value in bbob.groups())
        return make_problem(
            {
                "suite": "bbob",
                "function": function,
                "instance": instance,
                "dimension": dimension,
                "boundary_handling": "reflect",
            }
        )
    mabbob = re.fullmatch(r"mabbob_c(\d{3})_i(\d+)_d(\d+)", str(problem_id))
    if mabbob:
        candidate, instance, dimension = (int(value) for value in mabbob.groups())
        return make_problem(
            {
                "suite": "mabbob",
                "candidate_id": candidate,
                "instance": instance,
                "dimension": dimension,
                "boundary_handling": "reflect",
                "manifest_path": str(MABBOB_MANIFEST),
            }
        )
    raise ValueError(f"unsupported training problem_id: {problem_id}")


def _lshade_transfer_state(
    *,
    source_state: Any,
    problem: Any,
    seed: int,
    max_evaluations: int,
    event: int,
) -> LShadeState:
    population = np.asarray(source_state.population, dtype=float).copy()
    fitness = np.asarray(source_state.fitness, dtype=float).reshape(-1).copy()
    rng = make_event_rng(
        seed=int(seed),
        stream_code=LSHADE_TRANSFER_STREAM_CODE,
        suite_code=int(problem.suite_code),
        function=int(problem.function_number),
        instance=int(problem.instance_number),
        dimension=int(problem.dimension),
        generation=int(source_state.generation),
        event=int(event),
    )
    best_index = int(np.argmin(fitness))
    return LShadeState(
        population=population,
        fitness=fitness,
        archive=np.empty((0, int(problem.dimension)), dtype=float),
        memory_f=np.full(6, 0.5, dtype=float),
        memory_cr=np.full(6, 0.5, dtype=float),
        memory_index=0,
        generation=0,
        rng_state=deepcopy(rng.bit_generator.state),
        evaluations=0,
        max_evaluations=int(max_evaluations),
        initial_population_size=len(population),
        minimum_population_size=4,
        best_fitness=float(fitness[best_index]),
        best_position=population[best_index].copy(),
    )


def _reproduce_de_state(row: dict[str, Any]) -> tuple[Any, Any]:
    problem = _problem_from_id(str(row["problem_id"]))
    settings = OptimizerSettings(
        population_size=POPULATION_SIZE,
        checkpoint_ratios=(1.0,),
        boundary_handling="reflect",
    )
    state = initialize_optimizer_state(
        algorithm=PREFIX_ALGORITHM,
        problem=problem,
        seed=int(row["seed"]),
        settings=settings,
    )
    target_fe = int(row["FE"])
    while int(state.evaluations) < target_fe:
        step = min(POPULATION_SIZE, target_fe - int(state.evaluations))
        advance_optimizer_state(state=state, problem=problem, fe_budget=step)
    if int(state.evaluations) != target_fe:
        raise RuntimeError(
            f"DE reproduction ended at FE={state.evaluations}, expected {target_fe}"
        )
    return problem, state


def _generate_lshade_action(row: dict[str, Any]) -> dict[str, Any]:
    problem = None
    try:
        problem, de_state = _reproduce_de_state(row)
        if problem.reference_value is None:
            raise ValueError("training problem has no benchmark reference")
        expected_reference = float(row["benchmark_reference_value"])
        if not np.isclose(float(problem.reference_value), expected_reference, rtol=0.0, atol=1e-10):
            raise ValueError("reproduced problem reference differs from action-loss reference")
        budget = int(row["FE_action_optimization"])
        state = _lshade_transfer_state(
            source_state=de_state,
            problem=problem,
            seed=int(row["seed"]),
            max_evaluations=budget,
            event=QUERY_TRANSFER_EVENT,
        )
        advance_lshade_state(state=state, problem=problem, fe_budget=budget)
        continuation_gap = max(float(state.best_fitness) - expected_reference, 0.0)
        query_gap = max(float(row["query_best_gap"]), 0.0)
        action_gap = min(continuation_gap, query_gap)
        return {
            "problem_id": str(row["problem_id"]),
            "seed": int(row["seed"]),
            "FE": int(row["FE"]),
            "lshade_continuation_gap": float(continuation_gap),
            "lshade_action_loss": float(action_gap),
            "lshade_status": "completed",
        }
    except Exception as exc:
        return {
            "problem_id": str(row["problem_id"]),
            "seed": int(row["seed"]),
            "FE": int(row["FE"]),
            "lshade_continuation_gap": np.nan,
            "lshade_action_loss": np.nan,
            "lshade_status": f"failed:{type(exc).__name__}:{str(exc)[:180]}",
        }
    finally:
        if problem is not None:
            problem.close()


def _read_behavior_files() -> pd.DataFrame:
    frames: list[pd.DataFrame] = []
    roots = (
        (REPO / "results/phase1_refined_sampling/bbob_train", "bbob_train"),
        (REPO / "results/phase1_mabbob/mabbob_formal", "mabbob_formal"),
    )
    columns = [
        "problem_id",
        "function_id",
        "family",
        "cv_group_id",
        "dimension",
        "algorithm",
        "seed",
        "FE",
        *SELECTOR_BEHAVIOR_FEATURE_COLUMNS,
        *[column for column in DECISION_FEATURE_COLUMNS if column not in SELECTOR_BEHAVIOR_FEATURE_COLUMNS],
    ]
    for root, split in roots:
        for path in sorted(root.glob("**/behavior.parquet")):
            frame = pd.read_parquet(path)
            frame = frame[frame["dimension"].astype(int).eq(DIMENSION)].copy()
            frame = frame[frame["algorithm"].astype(str).eq(PREFIX_ALGORITHM)].copy()
            frame["split"] = split
            keep = [column for column in columns if column in frame.columns]
            frames.append(frame[["split", *keep]])
    if not frames:
        raise FileNotFoundError("no 10D DE behavior parquet files were found")
    output = pd.concat(frames, ignore_index=True)
    key = [
        "split",
        "problem_id",
        "function_id",
        "family",
        "cv_group_id",
        "dimension",
        "seed",
        "FE",
    ]
    if output.duplicated(key).any():
        raise ValueError("DE behavior files contain duplicate 10D state keys")
    return output


def _load_base_states() -> pd.DataFrame:
    if not SELECTION_REFERENCE.exists():
        raise FileNotFoundError(SELECTION_REFERENCE)
    source = pd.read_parquet(SELECTION_REFERENCE)
    source = source[
        source["split"].astype(str).isin({"bbob_train", "mabbob_formal"})
        & source["dimension"].astype(int).eq(DIMENSION)
        & source["prefix_algorithm"].astype(str).eq(PREFIX_ALGORITHM)
    ].copy()
    required = {
        "split",
        "problem_id",
        "function_id",
        "family",
        "cv_group_id",
        "dimension",
        "prefix_algorithm",
        "seed",
        "FE",
        "FE_ratio",
        "FE_total",
        "FE_prefix",
        "FE_query",
        "FE_action_optimization",
        "remaining_budget_ratio",
        "benchmark_reference_value",
        "query_best_gap",
        "p_skip",
        "observed_loss_de",
        "observed_loss_pso",
        "log10_gap_floor",
        "log10_gap_cap",
    }
    missing = sorted(required.difference(source.columns))
    if missing:
        raise ValueError(f"selection reference is missing required training columns: {missing}")
    source = source[
        [
            *sorted(required),
        ]
    ].drop_duplicates(
        [
            "split",
            "problem_id",
            "function_id",
            "family",
            "cv_group_id",
            "dimension",
            "prefix_algorithm",
            "seed",
            "FE",
        ]
    )
    source = source.rename(
        columns={
            "observed_loss_de": "action_loss_de",
            "observed_loss_pso": "action_loss_pso",
        }
    )

    query_spec = get_query_spec(MAIN_QUERY_ID)
    query = pd.concat(
        [pd.read_parquet(BBOB_FEATURES), pd.read_parquet(MABBOB_FEATURES)],
        ignore_index=True,
    )
    query = query[
        query["split"].astype(str).isin({"bbob_train", "mabbob_formal"})
        & query["dimension"].astype(int).eq(DIMENSION)
    ].copy()
    query_key = ["split", "problem_id", "function_id", "family", "dimension"]
    query_columns = [*query_key, "query_best_gap", *query_spec.feature_columns]
    query = query[query_columns].rename(columns={"query_best_gap": "query_best_gap_features"})
    if query.duplicated(query_key).any():
        raise ValueError("10D query features contain duplicate problem keys")
    source = source.merge(query, on=query_key, how="left", validate="many_to_one")
    if source[list(query_spec.feature_columns)].isna().all(axis=1).any():
        raise ValueError("some 10D training states lack query descriptors")

    behavior = _read_behavior_files()
    behavior_key = [
        "split",
        "problem_id",
        "function_id",
        "family",
        "cv_group_id",
        "dimension",
        "seed",
        "FE",
    ]
    source = source.merge(
        behavior[behavior_key + list(set(SELECTOR_BEHAVIOR_FEATURE_COLUMNS).union(DECISION_FEATURE_COLUMNS))],
        on=behavior_key,
        how="left",
        validate="one_to_one",
    )
    all_features = [*SELECTOR_BEHAVIOR_FEATURE_COLUMNS, *DECISION_FEATURE_COLUMNS]
    missing_features = [column for column in all_features if column not in source.columns]
    if missing_features:
        raise ValueError(f"training states lack behavior features: {missing_features}")
    if source[all_features].isna().all(axis=1).any():
        raise ValueError("some training states have no joined DE behavior row")
    return source.reset_index(drop=True)


def _build_training_states(*, workers: int, overwrite: bool) -> pd.DataFrame:
    output_path = OUTPUT / "training_states.parquet"
    if output_path.exists() and not overwrite:
        return pd.read_parquet(output_path)
    source = _load_base_states()
    jobs = source[
        [
            "problem_id",
            "seed",
            "FE",
            "FE_action_optimization",
            "benchmark_reference_value",
            "query_best_gap",
        ]
    ].to_dict(orient="records")
    worker_count = max(1, int(workers))
    print(f"Generating LSHADE outcomes for {len(jobs)} 10D DE states with {worker_count} workers", flush=True)
    if worker_count == 1:
        generated = [_generate_lshade_action(row) for row in jobs]
    else:
        with ProcessPoolExecutor(max_workers=worker_count) as executor:
            generated = list(executor.map(_generate_lshade_action, jobs, chunksize=1))
    lshade = pd.DataFrame(generated)
    failed = lshade[~lshade["lshade_status"].astype(str).eq("completed")]
    if not failed.empty:
        examples = failed["lshade_status"].astype(str).head(5).tolist()
        raise RuntimeError(f"LSHADE action generation failed for {len(failed)} states: {examples}")
    key = ["problem_id", "seed", "FE"]
    states = source.merge(lshade, on=key, how="left", validate="one_to_one")
    if states[["lshade_action_loss", "lshade_continuation_gap"]].isna().any().any():
        raise RuntimeError("LSHADE action outcomes did not cover every training state")
    states["action_loss_de"] = states["action_loss_de"].astype(float)
    states["action_loss_pso"] = states["action_loss_pso"].astype(float)
    states["lshade_action_loss"] = states["lshade_action_loss"].astype(float)
    losses = states[["action_loss_de", "action_loss_pso", "lshade_action_loss"]].to_numpy(float)
    floors = states["log10_gap_floor"].to_numpy(float)[:, None]
    caps = states["log10_gap_cap"].to_numpy(float)[:, None]
    log_losses = np.log10(np.minimum(np.maximum(losses, floors), caps))
    targets = log_losses - log_losses[:, [0]]
    for index, algorithm in enumerate(PORTFOLIO):
        states[f"selector_target_{algorithm}"] = targets[:, index]
    states["selector_target_transform"] = SELECTOR_TARGET_TRANSFORM
    states["selector_protocol"] = SELECTOR_PROTOCOL
    states["training_action_set"] = "de,pso,lshade"
    states["prefix_algorithm"] = PREFIX_ALGORITHM
    states["default_algorithm"] = PREFIX_ALGORITHM
    states["action_loss_status"] = "completed"
    OUTPUT.mkdir(parents=True, exist_ok=True)
    states.to_parquet(output_path, index=False)
    return states


